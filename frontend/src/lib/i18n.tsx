const DICTS: Record<UiLang, Dict> = { ru, en, zh };

interface I18nValue {
  lang: UiLang;
  setLang: (lang: UiLang) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nValue>({
  lang: "en",
  setLang: () => undefined,
  t: (key: string, fallback?: string) => fallback ?? key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UiLang>(() => {
    const stored = getUiLang();
    return (["ru", "en", "zh"].includes(stored) ? stored : "en") as UiLang;
  });

  const setLang = useCallback((next: UiLang) => {
    setLangState(next);
    setUiLang(next);
    document.documentElement.lang = next;
  }, []);

  const t = useCallback(
    (key: string, fallback?: string) => DICTS[lang][key] ?? DICTS.en[key] ?? fallback ?? key,
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

/** Локализованные названия типов разметки. */
